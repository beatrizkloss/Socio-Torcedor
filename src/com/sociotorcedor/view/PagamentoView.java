    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
         try {
            Torcedor torcedorSelecionado = (Torcedor) comboTorcedores.getSelectedItem();
            String data = campoDataPagamento.getText().trim();
            double valor = Double.parseDouble(campoValorPago.getText().trim().replace(",", "."));
            String metodo = (String) campoMetodoPagamento.getSelectedItem();
            
            controller.registrarPagamento(torcedorSelecionado, data, valor, metodo);
            
            JOptionPane.showMessageDialog(this, "Pagamento registrado com sucesso!");
            limparCampos();
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Erro: O campo 'Valor' deve ser um número válido.", "Erro de Formato", JOptionPane.ERROR_MESSAGE);
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, "Erro de Validação: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (idPagamentoSelecionado == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um pagamento na tabela para excluir.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        int resposta = JOptionPane.showConfirmDialog(this, "Tem certeza que deseja excluir este registro de pagamento?", "Confirmação", JOptionPane.YES_NO_OPTION);
        
        if (resposta == JOptionPane.YES_OPTION) {
            controller.excluir(idPagamentoSelecionado);
            limparCampos();
            JOptionPane.showMessageDialog(this, "Pagamento excluído com sucesso.");
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void tabelaPagamentoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelaPagamentoMouseClicked
        int linha = tabelaPagamento.getSelectedRow();
        if (linha != -1) {
            idPagamentoSelecionado = Integer.parseInt(String.valueOf(tabelaPagamento.getValueAt(linha, 0)));
        }
    }//GEN-LAST:event_tabelaPagamentoMouseClicked

    private void comboTorcedoresActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_comboTorcedoresActionPerformed
        Torcedor torcedorSelecionado = (Torcedor) comboTorcedores.getSelectedItem();
        if (torcedorSelecionado != null) {
            Plano planoDoTorcedor = torcedorSelecionado.getPlano();
            if (planoDoTorcedor != null) {
                double valorDoPlano = planoDoTorcedor.getValor();      
                campoValorPago.setText(String.valueOf(valorDoPlano));
            }
        } else {
            campoValorPago.setText("");
        }
    }//GEN-LAST:event_comboTorcedoresActionPerformed
 
