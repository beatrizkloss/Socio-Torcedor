    private void carregarTorcedoresNoComboBox() {
        List<Torcedor> torcedores = controller.listarTodosTorcedores();
        DefaultComboBoxModel<Torcedor> model = new DefaultComboBoxModel<>();

        for (Torcedor t : torcedores) {
            model.addElement(t);
        }
        comboTorcedores.setModel(model);
        comboTorcedores.setSelectedIndex(-1); // Garante que nada esteja selecionado no início
    }

    private void atualizarTabela(List<Pagamento> pagamentos) {
        DefaultTableModel model = (DefaultTableModel) tabelaPagamento.getModel();
        model.setRowCount(0);

        for (Pagamento p : pagamentos) {
            model.addRow(new Object[]{
                p.getId(),
                p.getTorcedor() != null ? p.getTorcedor().getNome() : "Torcedor não encontrado",
                p.getDataPagamento(),
                p.getValorPago(),
                p.getMetodoPagamento()
            });
        }
    }
    
    private void limparCampos() {
        comboTorcedores.setSelectedIndex(-1);
        campoDataPagamento.setText("");
        campoValorPago.setText("");
        campoMetodoPagamento.setSelectedIndex(0);
        idPagamentoSelecionado = -1;
        tabelaPagamento.clearSelection();
    }

