    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        try {
            // Pega os dados digitados pelo usuário nos campos de texto
            String nome = campoNomePlano.getText();
            double valor = Double.parseDouble(campoValorPlano.getText().replace(",", ".").trim()); 
            if (idPlanoSelecionado == -1) { // Se nenhum ID está selecionado, é um novo plano
                controller.salvar(nome, valor);
                JOptionPane.showMessageDialog(this, "Plano salvo com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            } else { // Se tem um ID, é uma atualização
                controller.atualizar(idPlanoSelecionado, nome, valor);
                JOptionPane.showMessageDialog(this, "Plano atualizado com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            }
            limparCampos();

        } catch (NumberFormatException e) {
            // Captura o erro se o usuário digitar um texto no campo de valor
            JOptionPane.showMessageDialog(this, "Erro: O campo 'Valor' deve ser um número válido.", "Erro de Formato", JOptionPane.ERROR_MESSAGE);
        } catch (IllegalArgumentException e) {
            // Captura os erros de validação que o Controller lança
            JOptionPane.showMessageDialog(this, "Erro de Validação: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (idPlanoSelecionado == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um plano na tabela para excluir.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        int resposta = JOptionPane.showConfirmDialog(this, "Tem certeza que deseja excluir este plano?", "Confirmação de Exclusão", JOptionPane.YES_NO_OPTION);
        
        if (resposta == JOptionPane.YES_OPTION) {
            controller.excluir(idPlanoSelecionado);
            JOptionPane.showMessageDialog(this, "Plano excluído com sucesso.");
            limparCampos(); // Limpa o formulário após a exclusão.
        }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void btnNovoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnNovoActionPerformed
        limparCampos();
    }//GEN-LAST:event_btnNovoActionPerformed

    private void tabelPlanosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelPlanosMouseClicked
        // Pega o número da linha que foi clicada na tabela.
        int linhaSelecionada = tabelPlanos.getSelectedRow();
        
        // Garante que uma linha foi realmente selecionada.
        if (linhaSelecionada != -1) {
            // Pega o valor do ID que está na primeira coluna (coluna 0) da linha selecionada.
            idPlanoSelecionado = Integer.parseInt(String.valueOf(tabelPlanos.getValueAt(linhaSelecionada, 0)));

            // Pega os outros dados da linha para preencher o formulário.
            String nome = (String) tabelPlanos.getValueAt(linhaSelecionada, 1);
            Object valorObj = tabelPlanos.getValueAt(linhaSelecionada, 2);

            // Preenche os campos do formulário para permitir a edição.
            campoNomePlano.setText(nome);
            campoValorPlano.setText(String.valueOf(valorObj));
        }
    }//GEN-LAST:event_tabelPlanosMouseClicked
    
