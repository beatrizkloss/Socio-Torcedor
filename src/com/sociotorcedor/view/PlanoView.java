    // Método auxiliar para carregar/atualizar os dados na JTable
     public void atualizarTabela(List<Plano> planos) {
            DefaultTableModel model = (DefaultTableModel) tabelPlanos.getModel();
            model.setRowCount(0);
             for (Plano p : planos) {
             model.addRow(new Object[]{
            p.getId(),
            p.getNome(),
            p.getValor()
        });
    }
}
    // método para limpar os campos do formulário
    private void limparCampos() {
        campoNomePlano.setText("");
        campoValorPlano.setText("");
        idPlanoSelecionado = -1; // reseta o ID selecionado
        tabelPlanos.clearSelection();
    }
