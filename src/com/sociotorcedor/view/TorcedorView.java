        // responsável por buscar os planos e preencher a caixa de seleção.
    private void carregarPlanosNoComboBox() {
        List<Plano> planos = controller.listarTodosPlanos();
        DefaultComboBoxModel<Plano> model = new DefaultComboBoxModel<>();
        for (Plano p : planos) {
            model.addElement(p);
        }
        comboPlanos.setModel(model);
    }

    // carregar/atualizar os dados na tabela de torcedores
    public void atualizarTabelaTorcedores(List<Torcedor> torcedores) {
        DefaultTableModel model = (DefaultTableModel) tabelaTorcedores.getModel();
        model.setRowCount(0);

        for (Torcedor t : torcedores) {
            model.addRow(new Object[]{
                t.getId(),
                t.getNome(),
                t.getCpf(),
                t.getEmail(),
                t.getPlano() != null ? t.getPlano().getNome() : ""
            });
        }
    }
    // Limpa os campos do formulário e reseta o ID selecionado.
    private void limparCampos() {
        campoNomeTorcedor.setText("");
        campoCpf.setText("");
        campoEmail.setText("");
        comboPlanos.setSelectedIndex(-1); // Desseleciona qualquer plano
        idTorcedorSelecionado = -1;
        tabelaTorcedores.clearSelection();
    }
