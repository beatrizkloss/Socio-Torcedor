    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        try {
            String nome = campoNomeTorcedor.getText().trim();
            String cpf = campoCpf.getText().trim();
            String email = campoEmail.getText().trim();
            Plano planoSelecionado = (Plano) comboPlanos.getSelectedItem();

            if (idTorcedorSelecionado == -1) { 
                controller.salvar(nome, cpf, email, planoSelecionado);
                JOptionPane.showMessageDialog(this, "Torcedor salvo com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            } else { 
                controller.atualizar(idTorcedorSelecionado, nome, cpf, email, planoSelecionado);
                JOptionPane.showMessageDialog(this, "Torcedor atualizado com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
            }
            limparCampos();
            
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, "Erro de Validação: " + e.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed
        if (idTorcedorSelecionado == -1) {
               JOptionPane.showMessageDialog(this, "Selecione um torcedor na tabela para excluir.", "Aviso", JOptionPane.WARNING_MESSAGE);
               return;
           }

           int resposta = JOptionPane.showConfirmDialog(this, "Tem certeza que deseja excluir este torcedor?", "Confirmação", JOptionPane.YES_NO_OPTION);

           if (resposta == JOptionPane.YES_OPTION) {
               controller.excluir(idTorcedorSelecionado);
               limparCampos();
               JOptionPane.showMessageDialog(this, "Torcedor excluído com sucesso.");
           }
    }//GEN-LAST:event_btnExcluirActionPerformed

    private void tabelaTorcedoresMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tabelaTorcedoresMouseClicked
        int linha = tabelaTorcedores.getSelectedRow();
         if (linha != -1) {
            idTorcedorSelecionado = Integer.parseInt(String.valueOf(tabelaTorcedores.getValueAt(linha, 0)));
            String nome = (String) tabelaTorcedores.getValueAt(linha, 1);
            String cpf = (String) tabelaTorcedores.getValueAt(linha, 2);
            String email = (String) tabelaTorcedores.getValueAt(linha, 3);

            campoNomeTorcedor.setText(nome);
            campoCpf.setText(cpf);
            campoEmail.setText(email);

            String nomePlanoNaTabela = (String) tabelaTorcedores.getValueAt(linha, 4);
            DefaultComboBoxModel<Plano> model = (DefaultComboBoxModel<Plano>) comboPlanos.getModel();
            for (int i = 0; i < model.getSize(); i++) {
                if (model.getElementAt(i).getNome().equals(nomePlanoNaTabela)) {
                    comboPlanos.setSelectedIndex(i);
                    break;
                }
            }
        }
    }//GEN-LAST:event_tabelaTorcedoresMouseClicked

